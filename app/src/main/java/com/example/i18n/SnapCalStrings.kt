    fun get(key: String, lang: SnapLanguage, vars: Map<String, Any> = emptyMap()): String {
        val dict = when (lang) {
            SnapLanguage.EN -> en
            SnapLanguage.AR -> ar
            SnapLanguage.FR -> fr
        }
        var raw = dict[key] ?: en[key] ?: key
        for ((varName, varVal) in vars) {
            raw = raw.replace("{$varName}", varVal.toString())
        }
        return raw
    }
}

@Composable
fun t(key: String, vars: Map<String, Any> = emptyMap()): String {
    val currentLang = LocalLanguage.current
    return SnapCalStrings.get(key, currentLang, vars)
